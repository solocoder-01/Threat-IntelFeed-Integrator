
import csv
import json
from pathlib import Path

from core.database import (
    DB_PATH,
    initialize_database,
    upsert_indicator,
    list_indicators,
)


BASE_DIR = Path(__file__).resolve().parent
INPUT_FILE = BASE_DIR / "data" / "scored_iocs.csv"
MAX_INPUT_BYTES = 5 * 1024 * 1024
MAX_ROWS = 100_000

REQUIRED_COLUMNS = {
    "indicator",
    "type",
    "sources",
    "source_count",
    "average_confidence",
    "source_bonus",
    "risk_score",
    "risk_level",
    "reasons",
}


def parse_int(value, field):
    value = value.strip()

    if not value.isascii() or not value.isdecimal():
        raise ValueError(f"Invalid integer in {field}")

    return int(value)


def main():
    if not INPUT_FILE.is_file():
        raise FileNotFoundError(
            f"Scored CSV not found: {INPUT_FILE}. "
            "Run python score_iocs.py first."
        )

    if INPUT_FILE.stat().st_size > MAX_INPUT_BYTES:
        raise ValueError("Input CSV exceeds the 5 MB safety limit")

    initialize_database()

    imported = 0
    rejected = 0

    with INPUT_FILE.open(
        "r", newline="", encoding="utf-8-sig"
    ) as file:
        reader = csv.DictReader(file)

        if not reader.fieldnames:
            raise ValueError("CSV is missing headers")

        reader.fieldnames = [
            name.strip().lower() if name else ""
            for name in reader.fieldnames
        ]

        if len(reader.fieldnames) != len(set(reader.fieldnames)):
            raise ValueError("Duplicate CSV headers are not allowed")

        missing = REQUIRED_COLUMNS - set(reader.fieldnames)
        if missing:
            raise ValueError(f"Missing columns: {sorted(missing)}")

        for row_number, row in enumerate(reader, start=1):
            if row_number > MAX_ROWS:
                raise ValueError("Input CSV exceeds the row limit")

            try:
                if None in row or any(v is None for v in row.values()):
                    raise ValueError("Malformed CSV row")

                sources_text = row["sources"].strip()
                sources = [
                    item.strip()
                    for item in sources_text.split(";")
                    if item.strip()
                ]

                reasons_text = row["reasons"].strip()
                reasons = [
                    item.strip()
                    for item in reasons_text.split(" | ")
                    if item.strip()
                ]

                # The CSV is generated by score_iocs.py, which currently
                # uses the same " | " separator for reasons.
                if not reasons_text:
                    raise ValueError("Missing scoring reasons")

                record = {
                    "indicator": row["indicator"].strip(),
                    "type": row["type"].strip().lower(),
                    "sources": sources,
                    "source_count": parse_int(
                        row["source_count"], "source_count"
                    ),
                    "average_confidence": parse_int(
                        row["average_confidence"], "average_confidence"
                    ),
                    "source_bonus": parse_int(
                        row["source_bonus"], "source_bonus"
                    ),
                    "risk_score": parse_int(
                        row["risk_score"], "risk_score"
                    ),
                    "risk_level": row["risk_level"].strip().upper(),
                    "reasons": reasons,
                }

                upsert_indicator(record)
                imported += 1

            except (ValueError, TypeError, KeyError) as error:
                rejected += 1
                print(f"Skipping row {row_number}: {error}")

    print("\n--- Database Import Summary ---")
    print(f"Imported/updated rows: {imported}")
    print(f"Rejected rows: {rejected}")
    print(f"Database: {DB_PATH}")

    print("\n--- Top Indicators ---")
    for item in list_indicators(limit=10):
        print(
            f"{item['risk_level']:6} | "
            f"Score {item['risk_score']:3} | "
            f"{item['indicator_type']:6} | "
            f"{item['indicator']}"
        )


if __name__ == "__main__":
    main()
